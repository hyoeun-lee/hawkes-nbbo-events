"""Figure legends page for submission: the captions of every figure environment in paper.tex,
numbered in order, typed together double-spaced on a separate page at the end of the manuscript.

The page is written between the markers
    % BEGIN figure legends
    % END figure legends
before \\end{document} (created if absent, replaced if present), so the script can be rerun after a
caption changes and the legends stay identical to the captions. Needs \\usepackage{setspace} in the
preamble, which the script adds after graphicx if missing.

    python scripts/make_figure_legends.py docs/paper/paper.tex
"""

import re
import sys


def balanced(s, i):
    """Text inside the brace group that opens at s[i] == '{', and the index after its closing brace."""
    assert s[i] == "{"
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "{":
            depth += 1
        elif s[j] == "}":
            depth -= 1
            if depth == 0:
                return s[i + 1:j], j + 1
    raise ValueError("unbalanced braces")


def figure_captions(tex):
    out = []
    for m in re.finditer(r"\\begin\{figure\}.*?\\end\{figure\}", tex, flags=re.S):
        block = m.group(0)
        k = block.find("\\caption{")
        if k < 0:
            continue
        cap, _ = balanced(block, k + len("\\caption"))
        out.append(cap.strip())
    return out


def main(path):
    tex = open(path).read()
    caps = figure_captions(tex)
    body = "\n\n".join(f"\\noindent\\textbf{{Figure {i}.}} {c}" for i, c in enumerate(caps, 1))
    page = ("% BEGIN figure legends (generated by scripts/make_figure_legends.py; rerun after a caption changes)\n"
            "\\clearpage\n\\section*{Figure Legends}\n\\begin{doublespace}\n" + body + "\n\\end{doublespace}\n"
            "% END figure legends\n")
    if "\\usepackage{setspace}" not in tex:
        tex = tex.replace("\\usepackage{graphicx}\n", "\\usepackage{graphicx}\n\\usepackage{setspace}   % double-spaced legends page\n", 1)
    if "% BEGIN figure legends" in tex:
        tex = re.sub(r"% BEGIN figure legends.*?% END figure legends\n", lambda _: page, tex, flags=re.S)
    else:
        tex = tex.replace("\\end{document}", page + "\n\\end{document}", 1)
    open(path, "w").write(tex)
    print(f"{len(caps)} figure legends written to {path}")


if __name__ == "__main__":
    main(sys.argv[1])
